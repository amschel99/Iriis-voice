"""Persistent storage: Postgres when DATABASE_URL is set (Railway), SQLite otherwise (local/offline).

One tiny interface for memories, notes, reminders and the audit log. SQL is written once with
`?` placeholders; for Postgres they become `%s`. Both engines support `INSERT ... RETURNING`
and `UPDATE ... RETURNING` (SQLite >= 3.35), which keeps reminder firing atomic.
"""
from __future__ import annotations

import os
import sqlite3
import threading
from pathlib import Path
from typing import Any

from iriis.config import resolve_path

DEFAULT_SQLITE = "data/iriis.sqlite3"

_TABLES = {
    "facts": "id {pk}, text TEXT NOT NULL, created {real} NOT NULL",
    "notes": "id {pk}, title TEXT, body TEXT NOT NULL, created {real} NOT NULL",
    "reminders": "id {pk}, text TEXT NOT NULL, due {real} NOT NULL, kind TEXT NOT NULL DEFAULT 'reminder', "
                 "fired INTEGER NOT NULL DEFAULT 0, created {real} NOT NULL",
    "audit_log": "id {pk}, ts TEXT NOT NULL, source TEXT NOT NULL, tool TEXT NOT NULL, tier TEXT, "
                 "executed INTEGER NOT NULL, entry TEXT NOT NULL",
    # Every user/assistant exchange; role 'reset' marks "start over" (older rows stay searchable).
    "messages": "id {pk}, session_id TEXT NOT NULL, role TEXT NOT NULL, content TEXT NOT NULL, created {real} NOT NULL",
    # Rolling summary of the parts of a conversation that no longer fit in the model's context.
    "conversation_summaries": "session_id TEXT PRIMARY KEY, summary TEXT NOT NULL, updated {real} NOT NULL",
}
_INDEXES = [
    "CREATE INDEX IF NOT EXISTS reminders_due ON reminders (fired, due)",
    "CREATE INDEX IF NOT EXISTS messages_session ON messages (session_id, id)",
]
_TYPES = {
    "sqlite": {"pk": "INTEGER PRIMARY KEY AUTOINCREMENT", "real": "REAL"},
    "postgres": {"pk": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "real": "DOUBLE PRECISION"},
}


class DB:
    def __init__(self, url: str | None = None, sqlite_path: str | Path | None = None):
        self.url = url or ""
        self.dialect = "postgres" if self.url.startswith(("postgres://", "postgresql://")) else "sqlite"
        self.path = Path(sqlite_path or resolve_path(DEFAULT_SQLITE))
        self._lock = threading.Lock()
        self._pg = None
        if self.dialect == "sqlite":
            self.path.parent.mkdir(parents=True, exist_ok=True)
        self._init_schema()

    @property
    def description(self) -> str:
        if self.dialect == "postgres":
            host = self.url.split("@")[-1].split("/")[0]
            return f"postgres ({host})"
        return f"sqlite ({self.path})"

    # ------------------------------------------------------------------ connections

    def _pg_conn(self):
        import psycopg
        if self._pg is None or self._pg.closed:
            self._pg = psycopg.connect(self.url, autocommit=True, connect_timeout=10)
        return self._pg

    def execute(self, sql: str, params: tuple | list = ()) -> list[tuple]:
        """Run one statement; returns rows for SELECT / ... RETURNING, else []."""
        if self.dialect == "sqlite":
            with sqlite3.connect(self.path, timeout=10) as c:
                cur = c.execute(sql, tuple(params))
                rows = cur.fetchall() if cur.description else []
            return rows
        import psycopg
        sql = sql.replace("?", "%s")
        with self._lock:
            for attempt in (1, 2):
                try:
                    cur = self._pg_conn().execute(sql, tuple(params))
                    return cur.fetchall() if cur.description else []
                except psycopg.OperationalError:
                    self._pg = None          # dropped connection: reconnect once
                    if attempt == 2:
                        raise
        return []

    def executemany(self, sql: str, rows: list[tuple]) -> None:
        """One batch, one transaction (used by the conversation write-behind buffer)."""
        if not rows:
            return
        if self.dialect == "sqlite":
            with sqlite3.connect(self.path, timeout=10) as c:
                c.executemany(sql, rows)
            return
        import psycopg
        sql = sql.replace("?", "%s")
        with self._lock:
            for attempt in (1, 2):
                try:
                    conn = self._pg_conn()
                    with conn.transaction(), conn.cursor() as cur:
                        cur.executemany(sql, rows)
                    return
                except psycopg.OperationalError:
                    self._pg = None
                    if attempt == 2:
                        raise

    def insert(self, sql: str, params: tuple | list = ()) -> int:
        return int(self.execute(sql + " RETURNING id", params)[0][0])

    def _init_schema(self) -> None:
        types = _TYPES[self.dialect]
        for name, cols in _TABLES.items():
            self.execute(f"CREATE TABLE IF NOT EXISTS {name} ({cols.format(**types)})")
        for idx in _INDEXES:
            self.execute(idx)


_dbs: dict[tuple[str, str], DB] = {}
_dbs_lock = threading.Lock()


def get_db(url: str | None = None, sqlite_path: str | None = None) -> DB:
    """Per-process shared DB. Defaults come from DATABASE_URL and IRIIS_SQLITE_PATH."""
    url = url if url is not None else os.environ.get("DATABASE_URL", "")
    sqlite_path = sqlite_path or os.environ.get("IRIIS_SQLITE_PATH") or str(resolve_path(DEFAULT_SQLITE))
    key = (url, sqlite_path)
    with _dbs_lock:
        if key not in _dbs:
            _dbs[key] = DB(url, sqlite_path)
        return _dbs[key]
